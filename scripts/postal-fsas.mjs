// Writes src/features/postal-check/fsa-data.ts: the place of every Ontario FSA (the first three
// characters of a postal code, K, L, M, N and P), and which of them are in the cities we
// deliver to. The source is Wikipedia's "List of postal codes of Canada: <letter>" tables,
// which follow Canada Post's FSA list. Run it to refresh the data, check the diff, commit:
//   pnpm postal-fsas
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../src/features/postal-check/fsa-data.ts", import.meta.url));
const LETTERS = ["K", "L", "M", "N", "P"];

// A place in the table -> the city (entities/area slug) it belongs to.
const CITY_OF_PLACE = {
  Mississauga: "mississauga",
  Brampton: "brampton",
  Vaughan: "vaughan",
  Woodbridge: "vaughan",
  Concord: "vaughan",
  Markham: "markham",
  "Richmond Hill": "richmond-hill",
};
// Thornhill straddles Yonge Street: the west side is Vaughan, the east side Markham.
const CITY_OF_FSA = { L4J: "vaughan", L3T: "markham" };
// Labels the table words oddly.
const PLACE_OVERRIDES = { M7A: "Queen's Park", K1A: "Ottawa" };
// M7R is a Canada Post sorting plant in Mississauga, not a neighbourhood.
const AREA_OVERRIDES = { M7R: null };

const COMPASS = /^(?:north|south|east|west|central|outer|ne|nw|se|sw|northeast|northwest|southeast|southwest|yyz)$/i;

async function fetchTable(letter) {
  const url = `https://en.wikipedia.org/w/index.php?title=List_of_postal_codes_of_Canada:_${letter}&action=raw`;
  const response = await fetch(url, { headers: { "user-agent": "washerrent.com postal data script" } });
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return response.text();
}

// One table cell's markup -> its lines of plain text.
function cellLines(markup) {
  return markup
    .replace(/\{\{resize\|[^|]*\|/g, "")
    .replace(/\[\[(?:[^\]|]*\|)?([^\]]*)\]\]/g, "$1")
    .replace(/<br\s*\/?>/g, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/\}\}|'''|''/g, "")
    .split("\n")
    .map((line) => line.trim().replace(/^\|+|\|+$/g, "").trim())
    .filter(Boolean);
}

// "(West Cooksville / Fairview / City Centre)" -> "West Cooksville"; directions alone -> null.
function areaOf(detail) {
  const items = detail
    .replace(/[()]/g, "")
    .split("/")
    .map((item) => item.replace(/, Ontario/g, "").trim())
    .filter(Boolean);
  const named = items.find((item) => !item.split(/\s+/).every((word) => COMPASS.test(word)));
  if (!named) return null;
  const words = named.split(/\s+/);
  // "NE Lakeview" -> "Lakeview"; "East Applewood" stays (a neighbourhood's own name).
  return /^(?:NE|NW|SE|SW)$/.test(words[0]) && words.length > 1 ? words.slice(1).join(" ") : named;
}

const places = {};
const delivery = {};
for (const letter of LETTERS) {
  const text = await fetchTable(letter);
  for (const match of text.matchAll(/'''([A-Z]\d[A-Z])'''(.*)/g)) {
    const [, fsa, rest] = match;
    const [place, ...detailLines] = cellLines(rest);
    if (!place || /not (?:assigned|in use)/i.test(place)) continue;
    // Rural FSAs (a 0 in second place, like L0J) cover wide mixed areas, some inside our
    // cities: left out, so their codes get "text us your address".
    if (fsa[1] === "0") continue;
    const name = PLACE_OVERRIDES[fsa] ?? place;
    const detail = detailLines.join(" ");
    const city = letter === "M" ? (place === "Mississauga" ? "mississauga" : "toronto") : (CITY_OF_FSA[fsa] ?? CITY_OF_PLACE[place]);
    if (city) {
      // Toronto: the district ("North York"). Elsewhere: the neighbourhood, or the community
      // inside the city (Woodbridge, Concord, Thornhill), or none.
      const cityName = { mississauga: "Mississauga", brampton: "Brampton", vaughan: "Vaughan", markham: "Markham", "richmond-hill": "Richmond Hill" }[city];
      const area = city === "toronto" ? name : (areaOf(detail) ?? (place === cityName ? null : place));
      const finalArea = fsa in AREA_OVERRIDES ? AREA_OVERRIDES[fsa] : area;
      // true when the area already names the city ("Downtown Toronto"): shown alone.
      const namesCity = Boolean(finalArea && finalArea.includes(city === "toronto" ? "Toronto" : cityName));
      delivery[fsa] = [city, finalArea, namesCity];
    } else {
      places[fsa] = name;
    }
  }
}

const entries = (object) =>
  Object.keys(object)
    .sort()
    .map((fsa) => `  ${fsa}: ${JSON.stringify(object[fsa])},`)
    .join("\n");

fs.writeFileSync(
  OUT,
  `// Generated by scripts/postal-fsas.mjs from Wikipedia's "List of postal codes of Canada"
// tables (K, L, M, N, P), which follow Canada Post's FSAs. Don't edit by hand: change the
// script and run \`pnpm postal-fsas\`.
import type { City } from "~/entities/area";

// FSAs in the cities we deliver to: [city, area or null, whether the area already names the
// city ("Downtown Toronto")]. Place names stay English.
export const DELIVERY_FSAS: Record<string, readonly [City["slug"], string | null, boolean]> = {
${entries(delivery)}
};

// Every other Ontario FSA, with its place.
export const FSA_PLACES: Record<string, string> = {
${entries(places)}
};
`,
);
console.log(`${Object.keys(delivery).length} delivery FSAs, ${Object.keys(places).length} other places -> ${OUT}`);
